// grokTestHome redirects the Grok target at a temp home. Tests using it must not
// run in parallel: it overrides a package-level resolver.
func grokTestHome(t *testing.T) string {
	t.Helper()
	home := t.TempDir()
	orig := configWebGrokConfigPathFn
	configWebGrokConfigPathFn = func() string { return filepath.Join(home, "config.toml") }
	t.Cleanup(func() { configWebGrokConfigPathFn = orig })
	return home
}

func grokTestWrite(t *testing.T, home, text string) string {
	t.Helper()
	path := filepath.Join(home, "config.toml")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func grokTestTarget(t *testing.T, home string) previewSyncTarget {
	t.Helper()
	target, ok := previewSyncTargetFor("grok", "llm-proxy-grok.toml")
	if !ok {
		t.Fatal("grok preview has no target")
	}
	return target
}

func TestConfigWebGrokModelRunSpan(t *testing.T) {
	t.Parallel()
	lines, _ := splitFileLines(grokTestConfig)
	span, ok := tomlModelRunSpan(lines)
	if !ok {
		t.Fatal("model run not located")
	}
	region := regionText(lines, span)
	if !strings.HasPrefix(region, `[model."grok-4.5"]`) {
		t.Fatalf("run must start at the first model table:\n%s", region)
	}
	if !strings.Contains(region, `base_url = "http://localhost:8892/v1"`) {
		t.Fatalf("run must include the last model table's body:\n%s", region)
	}
	// The neighbours a scanning mistake would pull in, and the table whose
	// header merely starts like a model table.
	for _, foreign := range []string{"[hints]", "[cli]", "[models]", "[telemetry]", "[privacy]", "tip_dismissed", "default_reasoning_effort"} {
		if strings.Contains(region, foreign) {
			t.Fatalf("run leaked %q:\n%s", foreign, region)
		}
	}
	if strings.HasSuffix(region, "\n\n") {
		t.Fatal("trailing blank lines stay outside the run")
	}
}

func TestConfigWebGrokModelRunBoundaries(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name  string
		lines []string
		want  bool
	}{
		{"no tables", []string{"[cli]", "vim_mode = false"}, false},
		{"global models only", []string{"[models]", `default = "x"`}, false},
		{"providers only", []string{"[model_providers.gw]", `base_url = "x"`}, false},
		{"array of tables", []string{"[[marketplace.sources]]", `name = "x"`}, false},
		{"single table", []string{"[model.a]", "x = 1"}, true},
		{"quoted and bare", []string{`[model."a.b"]`, "x = 1", "[model.c]", "y = 2"}, true},
		{"bodyless", []string{"[model.a]", "", "[telemetry]", "x = 1"}, true},
		{"nested belongs to run", []string{"[model.a]", "x = 1", "[model.a.extra]", "y = 2"}, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			_, ok := tomlModelRunSpan(tc.lines)
			if ok != tc.want {
				t.Fatalf("tomlModelRunSpan(%q) = %v, want %v", tc.lines, ok, tc.want)
			}
		})
	}
	// A bodyless table still yields the header line itself.
	span, _ := tomlModelRunSpan([]string{"[model.a]", "", "[telemetry]", "x = 1"})
	if span.Start != 1 || span.End != 1 {
		t.Fatalf("bodyless span = %+v, want 1..1", span)
	}
}

