func TestConfigWebGrokReportAttachesReadOnlyTarget(t *testing.T) {
	// Non-parallel: overrides the package-level target resolver.
	home := grokTestHome(t)
	grokTestWrite(t, home, grokTestConfig)
	report := inspectConfigWebDraft(lintValid, configModelsOptions{})
	var file *configWebFile
	for i := range report.Previews["grok"].Files {
		if report.Previews["grok"].Files[i].Name == "llm-proxy-grok.toml" {
			file = &report.Previews["grok"].Files[i]
		}
	}
	if file == nil {
		t.Fatal("grok preview file missing")
	}
	if file.TargetKind != configWebTargetFragment || file.TargetPath == "" {
		t.Fatalf("target = %+v", file)
	}
	if file.TargetEditable {
		t.Fatal("the grok preview must not advertise Save")
	}
	if !strings.HasPrefix(file.TargetContent, `[model."grok-4.5"]`) {
		t.Fatalf("on-disk region = %q", file.TargetContent)
	}
	if strings.HasPrefix(file.TargetPreview, "# ") || !strings.HasPrefix(file.TargetPreview, "[model.") {
		t.Fatalf("preview region = %q", file.TargetPreview)
	}
	if file.TargetHash == "" || file.TargetState != configWebTargetDiffer || file.TargetChanges == 0 {
		t.Fatalf("state=%q hash=%q changes=%d", file.TargetState, file.TargetHash, file.TargetChanges)
	}
}

func TestConfigWebGrokNeverWrites(t *testing.T) {
	// Non-parallel: overrides the package-level target resolver.
	home := grokTestHome(t)
	path := grokTestWrite(t, home, grokTestConfig)
	before, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	report := inspectConfigWebDraft(lintValid, configModelsOptions{})
	if report.Previews["grok"].Error != "" {
		t.Fatal(report.Previews["grok"].Error)
	}
	// The report locates and compares the region: nothing may be written, and no
	// lock or backup may appear next to the file.
	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != string(before) {
		t.Fatal("reporting the grok diff modified the file")
	}
	if stat, err := os.Stat(path); err != nil || !stat.ModTime().Equal(info.ModTime()) {
		t.Fatalf("mtime changed: %v -> %v (%v)", info.ModTime(), stat.ModTime(), err)
	}
	entries, err := os.ReadDir(home)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 || entries[0].Name() != "config.toml" {
		t.Fatalf("the grok target must leave no artifacts: %v", entries)
	}
}

func TestConfigWebGrokMissingFileAndNoTables(t *testing.T) {
	// Non-parallel: overrides the package-level target resolver.
	home := grokTestHome(t)
	target := grokTestTarget(t, home)
	state, region, hash, note, changes := syncTargetPreviewUpdate(target, grokTestPreview)
	if state != configWebTargetMissing || region != "" || hash != "" || note != "" || changes == 0 {
		t.Fatalf("absent file: state=%q region=%q hash=%q note=%q changes=%d", state, region, hash, note, changes)
	}
	// A file without model tables is missing too, and says so in its own terms.
	grokTestWrite(t, home, "[cli]\nvim_mode = false\n")
	state, region, hash, note, changes = syncTargetPreviewUpdate(target, grokTestPreview)
	if state != configWebTargetMissing || region != "" || hash == "" || changes == 0 {
		t.Fatalf("no tables: state=%q region=%q hash=%q changes=%d", state, region, hash, changes)
	}
	if !strings.Contains(note, "[model.*]") {
		t.Fatalf("note must name the model tables: %q", note)
	}
}

func TestConfigWebGrokDiffEndpointIsNotOffered(t *testing.T) {
	// Non-parallel: overrides the package-level target resolver.
	home := grokTestHome(t)
	grokTestWrite(t, home, grokTestConfig)
	handler := webTestHandler(webTestStore(t, lintValid))
	body := `{"text":` + strconvQuote(lintValid) + `,"runner":"grok","file":"llm-proxy-grok.toml"}`
	// Compare-only: the write endpoints stay closed even though the preview does
	// carry a located target.
	for _, path := range []string{"/api/diff", "/api/sync"} {
		if got := webTestRequest(handler, "POST", path, body); got.Code != 404 {
			t.Fatalf("%s status = %d, want 404: %s", path, got.Code, got.Body.String())
		}
	}
	// The report still carries the comparison the read-only panes render.
	loaded := webTestRequest(handler, "GET", "/api/config", "")
	var value struct {
		Report configWebReport `json:"report"`
	}
	if err := json.Unmarshal(loaded.Body.Bytes(), &value); err != nil {
		t.Fatal(err)
	}
	file := value.Report.Previews["grok"].Files[0]
	if file.TargetPreview == "" || file.TargetContent == "" || file.TargetEditable {
		t.Fatalf("grok file = %+v", file)
	}
}

func TestConfigWebGrokConfigPathResolution(t *testing.T) {
	// Not parallel: reads and restores the process environment.
	t.Setenv("GROK_HOME", filepath.Join(t.TempDir(), "custom-grok"))
	if got, want := configWebGrokConfigPath(), filepath.Join(os.Getenv("GROK_HOME"), "config.toml"); got != want {
		t.Fatalf("GROK_HOME resolved to %q, want %q", got, want)
	}
	t.Setenv("GROK_HOME", "   ")
	home, err := os.UserHomeDir()
	if err != nil {
		t.Skip("no home directory")
	}
	if got, want := configWebGrokConfigPath(), filepath.Join(home, ".grok", "config.toml"); got != want {
		t.Fatalf("blank GROK_HOME resolved to %q, want %q", got, want)
	}
	// The asset allowlist must serve the comparison module the panes import.
	if !configWebAssetAllowed("/model-run.mjs") {
		t.Fatal("model-run.mjs is not served")
	}
}
