func TestHTTPProxyGeneratedBytesIndependentOfConfig(t *testing.T) {
	resetHTTPProxyCache(t)
	var calls atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		calls.Add(1)
		fmt.Fprint(w, `{"data":[{"id":"zeta","reasoning_efforts":["low","high"],"default_reasoning_effort":"high"},{"id":"alpha"}]}`)
	}))
	defer server.Close()
	base := httpProxyTestDoc(server.URL)
	base.Models[0].ProviderModelName = "zeta"
	base.Models[0].DisplayName = "Curated name"
	base.Models[1].ProviderModelName = "unlisted"
	variants := []struct {
		name string
		edit func(*proxyConfig)
	}{
		{"unchanged", func(*proxyConfig) {}},
		{"route order", func(doc *proxyConfig) { doc.Models[0], doc.Models[1] = doc.Models[1], doc.Models[0] }},
		{"curated fields and variants", func(doc *proxyConfig) {
			n := 700000
			doc.Models[0].ClientModelName = "a-different-alias"
			doc.Models[0].DisplayName = "A different title"
			doc.Models[0].ContextWindow = &n
			doc.Models[0].Inputs = []configInput{{Type: "text"}, {Type: "image"}}
			doc.Models[0].Reasoning = &configReasoning{Disabled: true, DefaultEffort: "high"}
			doc.Models[0].Variants = []configVariant{{ClientModelName: "another-variant"}}
		}},
		{"no models", func(doc *proxyConfig) { doc.Models = []configModel{} }},
		{"mixed existing protocols", func(doc *proxyConfig) { doc.Models[0].Protocol = "anthropic-messages" }},
		{"other provider conflict", func(doc *proxyConfig) {
			doc.Providers = append(doc.Providers, configProvider{Name: "other", Kind: "http-proxy", BaseURL: "http://unused.invalid/v1", TokenFile: "/must-not-read-for-comparison"})
			doc.Models = append(doc.Models, configModel{Provider: "other", Protocol: "anthropic-messages", ProviderModelName: "foreign", ClientModelName: "gateway/alpha", Reasoning: &configReasoning{Disabled: true}})
		}},
		{"variant conflict", func(doc *proxyConfig) { doc.Models[0].Variants = []configVariant{{ClientModelName: "gateway/alpha"}} }},
		{"another route for same id", func(doc *proxyConfig) {
			route := doc.Models[0]
			route.ClientModelName = "second-alias"
			doc.Models = append(doc.Models, route)
		}},
	}
	var reference string
	for _, tc := range variants {
		t.Run(tc.name, func(t *testing.T) {
			// Deep-copy so neither the edits nor comparison can leak between cases.
			raw, _ := json.Marshal(base)
			var doc proxyConfig
			if err := json.Unmarshal(raw, &doc); err != nil {
				t.Fatal(err)
			}
			tc.edit(&doc)
			before, _ := json.Marshal(doc)
			probe, result, err := compareHTTPProxyCatalog(context.Background(), doc, "gateway", "openai-responses", false)
			if err != nil {
				t.Fatal(err)
			}
			text := catalogTestConfigText(t, doc)
			response, err := newHTTPProxyCompareResponse(probe, result, text)
			if err != nil {
				t.Fatal(err)
			}
			if reference == "" {
				reference = response.Generated
			}
			if response.Generated != reference {
				t.Fatalf("existing config changed generated bytes:\n%s", response.Generated)
			}
			if strings.Contains(response.Generated, "Curated") || strings.Contains(response.Generated, "unlisted") {
				t.Fatal("merged existing configuration")
			}
			if tc.name == "other provider conflict" || tc.name == "variant conflict" {
				if result.Stats.Conflicts != 1 || len(result.Generated) != 2 || !strings.Contains(response.Note, "still shown") {
					t.Fatalf("conflict filtered generation: %+v", result)
				}
			}
			if tc.name == "no models" && (result.Stats.Draft != 0 || result.Stats.Added != 2) {
				t.Fatalf("empty provider: %+v", result.Stats)
			}
			after, _ := json.Marshal(doc)
			if string(before) != string(after) {
				t.Fatal("comparison mutated config")
			}
			// Alphabetizing the on-disk keys must not change generated bytes either.
			var reordered map[string]any
			if err := json.Unmarshal([]byte(text), &reordered); err != nil {
				t.Fatal(err)
			}
			sortedText, _ := json.MarshalIndent(reordered, "", "  ")
			sorted, err := newHTTPProxyCompareResponse(probe, result, string(sortedText))
			if err != nil || sorted.Generated != reference {
				t.Fatalf("field order affected generation: %v", err)
			}
		})
	}
	if calls.Load() != 1 {
		t.Fatalf("cached catalog fetched %d times", calls.Load())
	}
	if strings.Index(reference, `"zeta"`) > strings.Index(reference, `"alpha"`) {
		t.Fatal("upstream model order was sorted")
	}
}

func TestHTTPProxyPureGenerationFixedTemplateAndNoMetadataInheritance(t *testing.T) {
	objects, err := generateHTTPProxyModels("gateway", "openai-responses", []httpProxyModelEntry{{ID: "z"}, {ID: "a"}})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"protocol", "provider", "providerModelName", "clientModelName", "displayName", "reasoning", "inputs"}
	for i, object := range objects {
		if strings.Join(object.keys, ",") != strings.Join(want, ",") {
			t.Fatalf("field order: %v", object.keys)
		}
		var model configModel
		if err := json.Unmarshal([]byte(object.text("")), &model); err != nil {
			t.Fatal(err)
		}
		if model.ContextWindow != nil || model.MaxTokens != nil || model.Compat != nil || len(model.Variants) != 0 || !model.Reasoning.Disabled {
			t.Fatalf("invented metadata: %+v", model)
		}
		if len(model.Inputs) != 2 || model.Inputs[0].Type != "text" || model.Inputs[1].Type != "image" {
			t.Fatalf("missing text + image defaults: %+v", model.Inputs)
		}
		if model.ProviderModelName != []string{"z", "a"}[i] {
			t.Fatal("sorted upstream list")
		}
	}
	reversed, err := generateHTTPProxyModels("gateway", "openai-responses", []httpProxyModelEntry{{ID: "a"}, {ID: "z"}})
	if err != nil || reversed[0].string("providerModelName") != "a" || catalogFragmentText(objects) == catalogFragmentText(reversed) {
		t.Fatalf("ignored upstream order: %v", err)
	}
}

func TestHTTPProxyDefaultInputsTextAndImageForBothProtocols(t *testing.T) {
	for _, protocol := range []string{"openai-responses", "anthropic-messages"} {
		t.Run(protocol, func(t *testing.T) {
			objects, err := generateHTTPProxyModels("gateway", protocol, []httpProxyModelEntry{
				{ID: "without-metadata"},
				{ID: "with-reasoning", ReasoningEfforts: []string{"low", "high"}, DefaultReasoningEffort: "high"},
			})
			if err != nil {
				t.Fatal(err)
			}
			var fragment struct {
				Models []configModel `json:"models"`
			}
			if err := json.Unmarshal([]byte(catalogFragmentText(objects)), &fragment); err != nil {
				t.Fatal(err)
			}
			for _, model := range fragment.Models {
				if len(model.Inputs) != 2 || model.Inputs[0].Type != "text" || model.Inputs[0].Disabled || model.Inputs[1].Type != "image" || model.Inputs[1].Disabled {
					t.Fatalf("inputs = %+v, want text and image enabled", model.Inputs)
				}
			}
			doc := proxyConfig{Listen: "127.0.0.1:8890", Providers: []configProvider{{Name: "gateway", Kind: "http-proxy", BaseURL: "http://example.invalid/v1"}}, Models: fragment.Models}
			routes, err := validateProxyConfig(doc)
			if err != nil {
				t.Fatal(err)
			}
			for _, route := range routes {
				if strings.Join(route.input, ",") != "text,image" {
					t.Fatalf("resolved inputs = %v", route.input)
				}
			}
		})
	}
}

func TestHTTPProxyAPIExplicitProtocolAndStableGeneration(t *testing.T) {
	resetHTTPProxyCache(t)
	var calls atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		calls.Add(1)
		fmt.Fprint(w, httpProxyTestPayload("existing", "new"))
	}))
	defer server.Close()
	doc := httpProxyTestDoc(server.URL)
	text := catalogTestConfigText(t, doc)
	handler := webTestHandler(webTestStore(t, text))
	for _, path := range []string{"/api/catalog-probe", "/api/catalog-compare"} {
		for _, protocol := range []string{"", "auto", "bogus"} {
			body, _ := json.Marshal(map[string]string{"text": text, "provider": "gateway", "protocol": protocol})
			w := webTestRequest(handler, "POST", path, string(body))
			if w.Code != 422 {
				t.Fatalf("%s protocol=%q: %d %s", path, protocol, w.Code, w.Body.String())
			}
		}
	}
	if calls.Load() != 0 {
		t.Fatal("missing protocol still fetched endpoint")
	}
	var expected string
	for _, models := range [][]configModel{doc.Models, {}, {doc.Models[1], doc.Models[0]}} {
		doc.Models = models
		body, _ := json.Marshal(map[string]string{"text": catalogTestConfigText(t, doc), "provider": "gateway", "protocol": "anthropic-messages"})
		w := webTestRequest(handler, "POST", "/api/catalog-compare", string(body))
		if w.Code != 200 {
			t.Fatalf("%d %s", w.Code, w.Body.String())
		}
		var response catalogCompareResponse
		if err := json.Unmarshal(w.Body.Bytes(), &response); err != nil {
			t.Fatal(err)
		}
		if expected == "" {
			expected = response.Generated
		}
		if response.Generated != expected || response.Protocol != "anthropic-messages" {
			t.Fatal("existing protocols/order affected generation")
		}
		if response.Stats.Draft != len(models) {
			t.Fatalf("on-disk count=%d", response.Stats.Draft)
		}
	}
	if calls.Load() != 1 {
		t.Fatalf("calls=%d", calls.Load())
	}
	rows := httpProxySummaryRows(doc)
	if rows[0].Protocol != "" || rows[0].Error != "" {
		t.Fatalf("summary inferred protocol: %+v", rows[0])
	}
}
